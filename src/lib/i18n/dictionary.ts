export const dictionaries: Record<Locale, Dictionary> = { en, zh };

export function isLocale(value: string | undefined | null): value is Locale {
  return value === "en" || value === "zh";
}

export function localeTag(locale: Locale): string {
  return locale === "zh" ? "zh-CN" : "en";
}

export function formatMessage(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export function pluralNoun(dict: Dictionary, count: number, key: "resource" | "learner" | "result" | "stage" | "week" | "searchNoun"): string {
  return count === 1 ? dict.common[key] : dict.common[`${key}_plural`];
}

export function pluralMessage(one: string, many: string, count: number, vars: Record<string, string | number> = {}): string {
  return formatMessage(count === 1 ? one : many, { count, ...vars });
}

export function facetLabel(dict: Dictionary, kind: "type" | "difficulty" | "language", value: string, fallback: string): string {
  if (kind === "type") {
    return dict.typesPlural[value as keyof typeof dict.typesPlural] ?? dict.types[value as keyof typeof dict.types] ?? fallback;
  }
  if (kind === "difficulty") {
    return dict.difficulty[value as keyof typeof dict.difficulty] ?? fallback;
  }
  return dict.languages[value as keyof typeof dict.languages] ?? fallback;
}

export function windowLabel(dict: Dictionary, days: number): string {
  if (days === 1) return dict.trendingPage.window24h;
  if (days === 7) return dict.trendingPage.window7d;
  if (days === 30) return dict.trendingPage.window30d;
  return dict.trendingPage.windowAll;
}
